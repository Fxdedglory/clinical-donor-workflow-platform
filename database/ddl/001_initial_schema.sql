CREATE SCHEMA IF NOT EXISTS staging;
CREATE SCHEMA IF NOT EXISTS operational;
CREATE SCHEMA IF NOT EXISTS marts;

-- Source of truth is the Alembic migration in database/migrations/versions.
-- This file is included for reviewers who want a quick schema orientation.

CREATE TABLE IF NOT EXISTS operational.dim_user (
    user_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name varchar(120) NOT NULL,
    email varchar(180) NOT NULL UNIQUE,
    role varchar(80) NOT NULL,
    department varchar(80) NOT NULL DEFAULT 'Clinical Operations',
    is_active boolean NOT NULL DEFAULT true
);

CREATE TABLE IF NOT EXISTS operational.fact_donor_review (
    review_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    donor_id varchar(40) NOT NULL UNIQUE,
    donor_name varchar(160) NOT NULL,
    age integer,
    blood_type varchar(8),
    infectious_history boolean NOT NULL DEFAULT false,
    travel_risk boolean NOT NULL DEFAULT false,
    missing_required_fields boolean NOT NULL DEFAULT false,
    risk_flags json NOT NULL,
    risk_score integer NOT NULL DEFAULT 0,
    risk_level varchar(40) NOT NULL DEFAULT 'Low',
    recommended_action varchar(80) NOT NULL DEFAULT 'Approve',
    review_priority varchar(40) NOT NULL DEFAULT 'Routine',
    intake_status varchar(40) NOT NULL DEFAULT 'Pending',
    reviewer_id integer REFERENCES operational.dim_user(user_id),
    clinical_notes text NOT NULL DEFAULT '',
    attachment_placeholder varchar(240) NOT NULL DEFAULT '',
    rejection_reason text,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    reviewed_at timestamptz
);

